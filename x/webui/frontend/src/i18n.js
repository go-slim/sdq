export const locale = computed(() => locales[activeLanguage.value] || locales.en);

export function t(key, parameters = {}) {
  const message = messages[activeLanguage.value]?.[key] ?? messages.en[key] ?? key;
  return message.replace(/\{([\w]+)\}/g, (match, name) => (
    Object.hasOwn(parameters, name) ? String(parameters[name]) : match
  ));
}

export function formatNumber(value, options = {}) {
  const number = Number(value ?? 0);
  return new Intl.NumberFormat(locale.value, options).format(Number.isFinite(number) ? number : 0);
}

export function installI18n(app) {
  app.config.globalProperties.$t = t;
  app.config.globalProperties.$formatNumber = formatNumber;

  return watch(activeLanguage, (language) => {
    document.documentElement.lang = language;
    document.title = t("app.title");
  }, {immediate: true});
}
